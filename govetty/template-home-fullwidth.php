  document.addEventListener("DOMContentLoaded", function () {
    const slider = document.querySelector(".frame-32");
    const navigationButtons = document.querySelectorAll("button.frame-31");
    const prevArrow = navigationButtons[0]; 
    const nextArrow = navigationButtons[1]; 

    if (!slider) return;

    // --- Drag Engine Tracking ---
    let isDown = false;
    let startX;
    let scrollLeft;

    slider.addEventListener("mousedown", (e) => {
      isDown = true;
      startX = e.pageX - slider.offsetLeft;
      scrollLeft = slider.scrollLeft;
    });

    slider.addEventListener("mouseleave", () => { isDown = false; });
    slider.addEventListener("mouseup", () => { isDown = false; });

    slider.addEventListener("mousemove", (e) => {
      if (!isDown) return;
      e.preventDefault();
      const x = e.pageX - slider.offsetLeft;
      const walk = (x - startX) * 1.5; 
      slider.scrollLeft = scrollLeft - walk;
    });

    // --- Custom Smooth Scroll Animation Engine ---
    // Controls how fast and smooth the arrows animate
    function smoothScrollTo(element, targetLocation, duration) {
      const startLocation = element.scrollLeft;
      const changeInLocation = targetLocation - startLocation;
      let startTime = null;

      // Easing function: Cubic Out (starts fast, slows down beautifully at the end)
      function easeCubicOut(time, start, change, duration) {
        time /= duration;
        time--;
        return change * (time * time * time + 1) + start;
      }

      function animationLoop(currentTime) {
        if (startTime === null) startTime = currentTime;
        const timeElapsed = currentTime - startTime;
        
        // Calculate the current step position using the easing equation
        element.scrollLeft = easeCubicOut(timeElapsed, startLocation, changeInLocation, duration);

        if (timeElapsed < duration) {
          requestAnimationFrame(animationLoop);
        } else {
          element.scrollLeft = targetLocation; // Ensure it locks perfectly onto the exact target pixel
        }
      }

      requestAnimationFrame(animationLoop);
    }

    // --- Button Actions ---
    const getScrollStep = () => {
      const firstCard = slider.querySelector(".frame-33");
      return firstCard ? firstCard.offsetWidth + 20 : 250;
    };

    if (prevArrow && nextArrow) {
      nextArrow.addEventListener("click", function () {
        const target = slider.scrollLeft + getScrollStep();
        // 800 is the duration in milliseconds (0.8 seconds). Increase this number for a slower glide!
        smoothScrollTo(slider, target, 800); 
      });

      prevArrow.addEventListener("click", function () {
        const target = slider.scrollLeft - getScrollStep();
        smoothScrollTo(slider, target, 800);
      });
    }
  });
</script>

